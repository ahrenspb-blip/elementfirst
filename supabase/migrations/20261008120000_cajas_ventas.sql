-- Cajas de las tiendas: cada caja se abre con un fondo, cobra las ventas de la tienda (efectivo,
-- Yape/Plin, tarjeta o transferencia), registra entradas, salidas y devoluciones de efectivo,
-- y se cierra contando el efectivo para ver si cuadra.
-- Los turnos, pagos y movimientos solo se escriben desde las funciones de abajo, que validan
-- permisos y ubicación; así nadie puede alterar el cuadre desde la API.
-- Se puede volver a ejecutar sin errores (no usa DROP).

-- ── Tablas ────────────────────────────────────────────────────────────────

create table if not exists public.cajas (
  id bigint generated by default as identity primary key,
  almacen_id bigint not null references public.almacenes (id),
  nombre text not null,
  activa boolean not null default true,
  creado_en timestamptz not null default now(),
  constraint cajas_nombre_largo check (char_length(btrim(nombre)) between 1 and 40)
);
create unique index if not exists cajas_nombre_unico on public.cajas (almacen_id, lower(btrim(nombre)));

create table if not exists public.caja_turnos (
  id bigint generated by default as identity primary key,
  caja_id bigint not null references public.cajas (id),
  almacen_id bigint not null references public.almacenes (id),
  estado text not null default 'abierta',
  abierta_por uuid not null references auth.users (id),
  abierta_por_nombre text,
  abierta_en timestamptz not null default now(),
  monto_inicial numeric(12, 2) not null,
  cerrada_por uuid references auth.users (id),
  cerrada_por_nombre text,
  cerrada_en timestamptz,
  efectivo_esperado numeric(12, 2),
  efectivo_contado numeric(12, 2),
  diferencia numeric(12, 2),
  conteo jsonb,
  nota_cierre text,
  constraint caja_turnos_estado check (estado in ('abierta', 'cerrada')),
  constraint caja_turnos_cierre check ((estado = 'abierta') = (cerrada_en is null)),
  constraint caja_turnos_montos check (monto_inicial >= 0 and (efectivo_contado is null or efectivo_contado >= 0)),
  constraint caja_turnos_nota check (nota_cierre is null or char_length(nota_cierre) <= 300)
);
-- Una caja no puede estar abierta dos veces, y cada persona tiene como máximo una caja abierta.
create unique index if not exists caja_turnos_una_abierta on public.caja_turnos (caja_id) where estado = 'abierta';
create unique index if not exists caja_turnos_usuario_abierta on public.caja_turnos (abierta_por) where estado = 'abierta';
create index if not exists caja_turnos_almacen on public.caja_turnos (almacen_id, abierta_en desc);

alter table public.ventas add column if not exists turno_id bigint references public.caja_turnos (id);
create index if not exists ventas_turno on public.ventas (turno_id) where turno_id is not null;

create table if not exists public.venta_pagos (
  id bigint generated by default as identity primary key,
  venta_id bigint not null references public.ventas (id) on delete cascade,
  turno_id bigint references public.caja_turnos (id),
  metodo text not null,
  monto numeric(12, 2) not null,
  operacion text,
  creado_en timestamptz not null default now(),
  constraint venta_pagos_metodo check (metodo in ('efectivo', 'yape_plin', 'tarjeta', 'transferencia')),
  constraint venta_pagos_monto check (monto > 0),
  constraint venta_pagos_operacion check (operacion is null or char_length(operacion) <= 40)
);
create index if not exists venta_pagos_venta on public.venta_pagos (venta_id);
create index if not exists venta_pagos_turno on public.venta_pagos (turno_id) where turno_id is not null;

create table if not exists public.caja_movimientos (
  id bigint generated by default as identity primary key,
  turno_id bigint not null references public.caja_turnos (id),
  tipo text not null,
  monto numeric(12, 2) not null,
  motivo text not null,
  venta_id bigint references public.ventas (id),
  registrado_por uuid references auth.users (id),
  registrado_por_nombre text,
  creado_en timestamptz not null default now(),
  constraint caja_movimientos_tipo check (tipo in ('entrada', 'salida', 'devolucion')),
  constraint caja_movimientos_monto check (monto > 0),
  constraint caja_movimientos_motivo check (char_length(btrim(motivo)) between 1 and 160)
);
create index if not exists caja_movimientos_turno on public.caja_movimientos (turno_id);
create index if not exists caja_movimientos_venta on public.caja_movimientos (venta_id) where venta_id is not null;

