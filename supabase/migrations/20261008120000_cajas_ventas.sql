      with check ((select public.tiene_permiso('almacenes'))
                  and exists (select 1 from public.almacenes a where a.id = almacen_id and a.tipo = 'tienda'));
  end if;
  if not exists (select 1 from pg_policies where policyname = 'cajas_editar' and tablename = 'cajas') then
    create policy cajas_editar on public.cajas for update to authenticated
      using ((select public.tiene_permiso('almacenes')))
      with check ((select public.tiene_permiso('almacenes')));
  end if;
  if not exists (select 1 from pg_policies where policyname = 'caja_turnos_leer' and tablename = 'caja_turnos') then
    create policy caja_turnos_leer on public.caja_turnos for select to authenticated
      using ((select public.puede_ver('{ventas,dashboard,reportes}'::text[]))
             and ((select public.ubicacion_restringida()) is null or almacen_id = (select public.ubicacion_restringida())));
  end if;
  -- Pagos y movimientos se ven si se ve la venta o el turno (las políticas de esas tablas se aplican).
  if not exists (select 1 from pg_policies where policyname = 'venta_pagos_leer' and tablename = 'venta_pagos') then
    create policy venta_pagos_leer on public.venta_pagos for select to authenticated
      using (exists (select 1 from public.ventas v where v.id = venta_id));
  end if;
  if not exists (select 1 from pg_policies where policyname = 'caja_movimientos_leer' and tablename = 'caja_movimientos') then
    create policy caja_movimientos_leer on public.caja_movimientos for select to authenticated
      using (exists (select 1 from public.caja_turnos t where t.id = turno_id));
  end if;
end $$;

